import fs from "node:fs/promises";
import path from "node:path";

const cwd = process.cwd();
const root = path.join(cwd, "public", "unity-import");

const modelExt = new Set([".obj", ".fbx", ".glb", ".gltf"]);
const imageExt = new Set([".png", ".jpg", ".jpeg", ".webp", ".bmp", ".tga"]);
const audioExt = new Set([".mp3", ".wav", ".ogg"]);
const materialExt = new Set([".mtl"]);

function toPosix(p) {
  return p.split(path.sep).join("/");
}

function slugId(relPath) {
  return `idx-${relPath.toLowerCase().replace(/[^a-z0-9/._-]+/g, "-").replace(/[/.]/g, "-")}`;
}

function inferGroup(lowered) {
  if (lowered.includes("/resources/exported/")) return "exported";
  if (lowered.includes("/extracted/")) return "extracted";
  if (lowered.includes("/game/")) return "game";
  if (lowered.includes("/tilesets/")) return "tilesets";
  if (lowered.includes("/asset packs/")) return "asset-packs";
  if (lowered.includes("/realistic effects pack/")) return "effects-pack";
  return "misc";
}

function inferKind(ext, lowered) {
  if (modelExt.has(ext)) {
    if (lowered.includes("/animations/") || lowered.includes("_animations/")) return "animation";
    return "model";
  }
  if (imageExt.has(ext)) return "texture";
  if (audioExt.has(ext)) return "audio";
  if (materialExt.has(ext)) return "material";
  return "other";
}

async function walk(dir) {
  const out = [];
  const stack = [dir];
  while (stack.length > 0) {
    const current = stack.pop();
    if (!current) continue;
    let entries = [];
    try {
      entries = await fs.readdir(current, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const e of entries) {
      const full = path.join(current, e.name);
      if (e.isDirectory()) stack.push(full);
      else if (e.isFile()) out.push(full);
    }
  }
  return out;
}

async function pickPreviewForModel(modelAbsPath) {
  const dir = path.dirname(modelAbsPath);
  const base = path.basename(modelAbsPath, path.extname(modelAbsPath)).toLowerCase();
  let entries = [];
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return undefined;
  }
  const imageNames = entries
    .filter((e) => e.isFile() && imageExt.has(path.extname(e.name).toLowerCase()))
    .map((e) => e.name);
  if (!imageNames.length) return undefined;
  const exact = imageNames.find((n) => path.basename(n, path.extname(n)).toLowerCase() === base);
  const starts = imageNames.find((n) => path.basename(n, path.extname(n)).toLowerCase().startsWith(base));
  const chosen = exact ?? starts ?? imageNames.sort()[0];
  return `/${toPosix(path.relative(path.join(cwd, "public"), path.join(dir, chosen)))}`;
}

async function main() {
  const files = await walk(root);
  files.sort((a, b) => a.localeCompare(b));

  const rows = [];
  for (const absPath of files) {
    const relPublic = toPosix(path.relative(path.join(cwd, "public"), absPath));
    const relLower = relPublic.toLowerCase();
    const ext = path.extname(relPublic).toLowerCase();
    const kind = inferKind(ext, relLower);
    const group = inferGroup(relLower);
    let previewImage;
    if (kind === "texture") previewImage = `/${relPublic}`;
    else if (kind === "model") previewImage = await pickPreviewForModel(absPath);

    rows.push({
      id: slugId(relPublic),
      path: `/${relPublic}`,
      ext,
      kind,
      group,
      previewImage,
    });
  }

  const outFile = path.join(cwd, "src", "world", "unity-import-index.generated.ts");
  const source =
    `/* eslint-disable */\n` +
    `// Auto-generated by tools/generate-unity-import-index.mjs\n` +
    `// Do not edit manually.\n\n` +
    `export type UnityImportIndexEntry = {\n` +
    `  id: string;\n` +
    `  path: string;\n` +
    `  ext: string;\n` +
    `  kind: "model" | "animation" | "texture" | "audio" | "material" | "other";\n` +
    `  group: "exported" | "extracted" | "game" | "tilesets" | "asset-packs" | "effects-pack" | "misc";\n` +
    `  previewImage?: string;\n` +
    `};\n\n` +
    `export const UNITY_IMPORT_INDEX: UnityImportIndexEntry[] = ${JSON.stringify(rows, null, 2)};\n`;

  await fs.writeFile(outFile, source, "utf8");
  console.log(`Generated ${rows.length} unity-import index rows -> ${outFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});

