import fs from "node:fs/promises";
import path from "node:path";

const cwd = process.cwd();
const modelExt = new Set([".obj", ".fbx", ".glb", ".gltf"]);
const imageExt = new Set([".png", ".jpg", ".jpeg", ".webp"]);

const roots = [path.join(cwd, "public", "unity-import")];

function toPosix(p) {
  return p.split(path.sep).join("/");
}

function slugId(relNoExt) {
  return `auto-${relNoExt.toLowerCase().replace(/[^a-z0-9/._-]+/g, "-").replace(/[/.]/g, "-")}`;
}

async function walk(dir) {
  const out = [];
  const stack = [dir];
  while (stack.length > 0) {
    const current = stack.pop();
    if (!current) continue;
    let entries = [];
    try {
      entries = await fs.readdir(current, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const e of entries) {
      const full = path.join(current, e.name);
      if (e.isDirectory()) stack.push(full);
      else if (e.isFile()) out.push(full);
    }
  }
  return out;
}

async function fileExists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function pickPreview(modelPath) {
  const dir = path.dirname(modelPath);
  const base = path.basename(modelPath, path.extname(modelPath)).toLowerCase();
  const candidates = [];
  let entries = [];
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return undefined;
  }
  for (const e of entries) {
    if (!e.isFile()) continue;
    const ext = path.extname(e.name).toLowerCase();
    if (!imageExt.has(ext)) continue;
    candidates.push(e.name);
  }
  if (candidates.length === 0) return undefined;

  const exact = candidates.find((n) => path.basename(n, path.extname(n)).toLowerCase() === base);
  const starts = candidates.find((n) => path.basename(n, path.extname(n)).toLowerCase().startsWith(base));
  const pick = exact ?? starts ?? candidates.sort()[0];
  return path.join(dir, pick);
}

async function main() {
  const modelFiles = [];
  for (const root of roots) {
    const files = await walk(root);
    for (const f of files) {
      if (modelExt.has(path.extname(f).toLowerCase())) modelFiles.push(f);
    }
  }

  modelFiles.sort((a, b) => a.localeCompare(b));

  const rows = [];
  for (const filePath of modelFiles) {
    const relToPublic = toPosix(path.relative(path.join(cwd, "public"), filePath));
    const relNoExt = relToPublic.replace(/\.[^.]+$/, "");
    const id = slugId(relNoExt);
    const previewAbs = await pickPreview(filePath);
    const previewRel = previewAbs && (await fileExists(previewAbs))
      ? `/${toPosix(path.relative(path.join(cwd, "public"), previewAbs))}`
      : undefined;

    const lowered = relToPublic.toLowerCase();
    if (lowered.includes("/animations/") || lowered.includes("_animations/")) continue;
    const isMapChunk = lowered.includes("/maps/") || /adt_\d+_\d+\.obj$/.test(lowered);
    const isWmo = lowered.includes("/wmo/");
    const ext = path.extname(filePath).toLowerCase();

    let animationSources;
    if (ext === ".fbx") {
      const baseName = path.basename(filePath, ext);
      const animDir = path.join(path.dirname(filePath), `${baseName}_Animations`);
      const animFiles = (await walk(animDir))
        .filter((p) => path.extname(p).toLowerCase() === ".fbx")
        .sort((a, b) => a.localeCompare(b));
      if (animFiles.length) {
        animationSources = animFiles.map((p) => `/${toPosix(path.relative(path.join(cwd, "public"), p))}`);
      }
    }

    rows.push({
      id,
      path: `/${relToPublic}`,
      previewImage: previewRel,
      animationSources,
      position: { x: 0, y: 0, z: 0 },
      rotationY: 0,
      scale: 1,
      placeOnGround: !isMapChunk,
      collider: isWmo,
      defaultSpawn: false,
    });
  }

  const outFile = path.join(cwd, "src", "world", "unity-exported-decor.generated.ts");
  const header = `/* eslint-disable */\n// Auto-generated by tools/generate-unity-exported-decor.mjs\n// Do not edit manually.\n\nimport type { UnityDecorationConfig } from "./unity-decor.config";\n\nexport const UNITY_EXPORTED_DECORATIONS: UnityDecorationConfig[] = `;
  const source = `${header}${JSON.stringify(rows, null, 2)};\n`;
  await fs.writeFile(outFile, source, "utf8");
  console.log(`Generated ${rows.length} exported decorations -> ${outFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
